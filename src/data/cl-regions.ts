export const REGION_NAMES = CL_REGIONS.map((r) => r.name);

export function comunasOf(regionName: string): string[] {
  return CL_REGIONS.find((r) => r.name === regionName)?.comunas ?? [];
}

export function isValidLocation(region: string, comuna: string): boolean {
  return comunasOf(region).includes(comuna);
}
